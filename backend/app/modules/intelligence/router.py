AiReview = Annotated[CurrentUser, Depends(require("grievance.read", "ai.review"))]


def _c(c: AIClassification, reviewer: str | None = None) -> dict[str, Any]:
    return {
        "id": str(c.id),
        "task": c.task,
        "model_id": c.model_id,
        "model_version": c.model_version,
        "prediction": c.prediction,
        "confidence": float(c.confidence) if c.confidence is not None else None,
        "input_ref": c.input_ref,
        "processing_status": c.processing_status,
        "evidence": c.evidence,
        "verification_status": c.verification_status,
        "verified_value": c.verified_value,
        "verified_by": reviewer,
        "verified_at": c.verified_at,
        "review_note": c.review_note,
        "created_at": c.created_at,
    }


@router.get("/grievances/{grievance_id}/intelligence")
def grievance_intel(grievance_id: uuid.UUID, cu: AiRead, db: DbDep) -> dict[str, Any]:
    g = gsvc.get_scoped(db, cu, grievance_id)
    rev = aliased(User)
    rows = db.execute(
        select(AIClassification, rev.full_name)
        .outerjoin(rev, rev.id == AIClassification.verified_by)
        .where(AIClassification.grievance_id == g.id)
        .order_by(AIClassification.created_at.desc())
    ).all()
    other = aliased(Grievance)
    dups = db.execute(
        select(DuplicateCandidate, other.reference_no, other.subject, other.status)
        .join(other, other.id == DuplicateCandidate.candidate_grievance_id)
        .where(DuplicateCandidate.grievance_id == g.id, grievance_scope(cu).self_group())
        .order_by(DuplicateCandidate.similarity.desc())
    ).all()
    return {
        "classifications": [_c(c, r) for c, r in rows],
        "duplicates": [
            {
                "id": str(d.id),
                "candidate_grievance_id": str(d.candidate_grievance_id),
                "reference_no": ref,
                "subject": subj,
                "status": st,
                "similarity": float(d.similarity),
                "method": d.method,
                "evidence": d.evidence,
                "review_status": d.status,
            }
            for d, ref, subj, st in dups
        ],
        "notice": "Suggestions are generated by explainable rules and require officer review. They never change a "
        "grievance on their own.",
    }


class ReviewIn(BaseModel):
    decision: Literal["accept", "edit", "reject"]
    value: dict[str, Any] | None = None
    note: str | None = Field(default=None, max_length=1000)


@router.post("/intelligence/classifications/{classification_id}/review")
def review(classification_id: uuid.UUID, body: ReviewIn, request: Request, cu: AiReview, db: DbDep) -> dict[str, Any]:
    c = service.review_classification(
        db,
        cu,
        classification_id,
        body.decision,
        body.value,
        body.note,
        RequestMeta.from_request(request),
    )
    return _c(c)


class DupReview(BaseModel):
    confirm: bool


@router.post("/intelligence/duplicates/{duplicate_id}/review")
def review_duplicate(
    duplicate_id: uuid.UUID, body: DupReview, request: Request, cu: AiReview, db: DbDep
) -> dict[str, Any]:
    d = service.review_duplicate(db, cu, duplicate_id, body.confirm, RequestMeta.from_request(request))
    return {"id": str(d.id), "status": d.status}


@router.post("/grievances/{grievance_id}/intelligence/run")
def rerun(grievance_id: uuid.UUID, cu: AiReview, db: DbDep) -> dict[str, Any]:
    g = gsvc.get_scoped(db, cu, grievance_id)
    return service.analyse(db, g.id)


@router.get("/intelligence/clusters")
def clusters(cu: AiRead, db: DbDep, emerging_only: bool = False) -> list[dict[str, Any]]:
    rows = db.execute(
        select(GrievanceCluster, IssueCategory.name_en)
        .outerjoin(IssueCategory, IssueCategory.id == GrievanceCluster.category_id)
        .order_by(GrievanceCluster.open_count.desc())
        .limit(200)
    ).all()
    out = []
    for cl, cat in rows:
        visible = (
            db.execute(
                select(ClusterMember.grievance_id)
                .join(Grievance, Grievance.id == ClusterMember.grievance_id)
                .where(ClusterMember.cluster_id == cl.id, grievance_scope(cu))
            )
            .scalars()
            .all()
        )
        if not visible:
            continue
        out.append(
            {
                "id": str(cl.id),
                "category": cat,
                "unit_level": cl.unit_level,
                "unit_id": str(cl.unit_id),
                "window_start": cl.window_start,
                "window_end": cl.window_end,
                "grievance_count": cl.grievance_count,
                "open_count": cl.open_count,
                "visible_grievance_ids": [str(v) for v in visible],
                "evidence": cl.evidence,
                "method_version": cl.method_version,
            }
        )
    return out


